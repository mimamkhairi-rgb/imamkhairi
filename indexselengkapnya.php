            <h2>Strategi Ini Bisa Bikin RI Capai Target Pertumbuhan Ekonomi 8 Persen</h2>
            <img src="images/Header3.png" alt="Gambar Artikel">
            <p>
                The administration of President Prabowo Subianto and Vice President Gibran Rakabuming Raka is targeting Indonesia’s economic growth to reach 8 percent. Economist and Expert Staff to the Coordinating Minister for Economic Affairs, Raden Pardede, stated that the formula for achieving 8 percent economic growth is not complicated. “All of the engines must operate optimally. What are these engines? The first is the investment engine, which must run effectively; the second is productivity that must also operate optimally. The government machinery must be efficient, and the external engine—exports—must also function properly. That’s the formula,” he said during the Discussion Forum on One Year Achievements of the Red and White Cabinet in the Economic Sector, titled ‘Economic Progress Toward Asta Cita: How Far Have We Come’. In addition, he emphasized that capital accumulation must continue to be strengthened to build the confidence needed to reach the 8 percent growth target. “For foreign investors, what matters most is certainty and clarity,” he added. He further mentioned that regulators are expected to create clear and transparent regulations to welcome foreign investments, including defining investment limits and business activities that foreign investors are allowed to undertake. “That, I believe, will ensure the investment engine runs smoothly,” he explained. Furthermore, Raden noted that achieving strong economic growth requires more than just the combination of labor, human capital, and investment.
